import numpy as np
import geopandas as gpd
import matplotlib.pyplot as plt
import pandas as pd
import os
import re
import rioxarray as rxr
import torch
import xarray as xr
import xml.etree.ElementTree as ET

from abc import ABC, abstractmethod
from collections import Counter
from matplotlib.colors import ListedColormap
from matplotlib.patches import Patch
from tqdm import tqdm


class BaseDataset(torch.utils.data.Dataset, ABC):
    RGB_BANDS = None  # dataset-specific RGB bands

    def __init__(
        self,
        meta_file,
        input_data_dir=None,
        label_data_dir=None,
        sel_time=None,
        sel_band=None,
        data_transform=None,
        data_usage=0,
        check_congruence=False,
    ):
        """
        Base Dataset class.

        Args:
            meta_file (str, gpd.GeoDataFrame): GeoJSON metadata file or dataframe with patch information,
                can be either...
                a) the original metadata file/df with columns 'row', 'col' as produced during data generation
                b) the extended metadata file/df with additional columns 'folds_', 'input_path' and 'label_path'
                as generated by applying the cross-validation script (crossval.py)
            input_data_dir (str): Directory containing the input data files (e.g. S-2 or DOP).
                Optional if extended metadata file is provided.
            label_data_dir (str): Directory containing the habitat label files.
                Optional if extended metadata file is provided.
            sel_time (list, optional): List of time steps to select from the dataset.
            sel_band (list, optional): List of bands to select from the dataset.
            data_usage (int, optional): How to use/preprocess the label data
                - 0: full label data (multi-class), default
                - 1: binary label data (habitat vs. non-habitat)
            data_transform (callable, optional): A function/transform to apply to the images
            check_congruence (bool, optional): Whether to check congruence between metadata and data directories.
                Defaults to False, since the check can be expensive for large datasets. If True, raises an error
                if the number of entries in metadata does not match the number of files in the data and label
                directories or if the unqiue labels in the arrays do not match the expected labels.
        """
        # parse input parameters
        if isinstance(meta_file, str):
            self.meta_file = gpd.read_file(meta_file).reset_index(drop=True)
        else:
            self.meta_file = meta_file.reset_index(drop=True)
        if "input_path" in self.meta_file.columns:
            self.data_dir = os.path.split(self.meta_file["input_path"].iloc[0])[0]
        else:
            self.data_dir = input_data_dir
        if "label_path" in self.meta_file.columns:
            self.label_dir = os.path.split(self.meta_file["label_path"].iloc[0])[0]
        else:
            self.label_dir = label_data_dir
        self.sel_time = sel_time
        self.sel_band = sel_band
        self.data_transform = data_transform
        self.data_usage = data_usage
        self.check_congruence = check_congruence

        # define label map
        if self.data_usage == 0:
            self._get_label_map(binary=False)
        elif self.data_usage == 1:
            self._get_label_map(binary=True)

        # add file paths to the meta file
        if "input_path" not in self.meta_file.columns:
            file_paths = {}
            label_files = [
                os.path.join(self.label_dir, f)
                for f in os.listdir(self.label_dir)
                if f.endswith(".tif") or f.endswith(".vrt")
            ]
            data_files = [
                os.path.join(self.data_dir, f)
                for f in os.listdir(self.data_dir)
                if f.endswith(".tif") or f.endswith(".vrt")
            ]
            pattern = re.compile(r"_r(\d+)c(\d+)\.(?:vrt|tif)")
            for name, paths in [
                ("label_path", label_files),
                ("input_path", data_files),
            ]:
                file_map = {}
                for f in paths:
                    match = pattern.search(f)
                    if match:
                        row, col = map(int, match.groups())
                        file_map[(row, col)] = f
                file_paths = self.meta_file.apply(
                    lambda row: file_map.get((row["row"], row["col"])), axis=1
                )
                self.meta_file.insert(0, name, file_paths)

        # get time and band selection indices
        exp_file = self.meta_file["input_path"].iloc[0]
        filenames = self._get_source_filenames_from_vrt(exp_file)
        file_times_bands = self._parse_filenames(filenames)
        exp_ds = rxr.open_rasterio(exp_file)
        exp_ds = exp_ds.assign_coords(
            band=("band", [f[1] for f in file_times_bands]),
            time=("band", [f[0] for f in file_times_bands]),
        )
        if self.sel_band is None:
            self.sel_band = list(np.unique(exp_ds.band.values))
        else:
            if not all(b in exp_ds.band.values for b in self.sel_band):
                raise ValueError(
                    f"""
                    Selected bands {self.sel_band} are not present in the dataset.
                    Available bands: {np.unique(exp_ds.band.values)}
                    """
                )
        if self.sel_time is None:
            self.sel_time = list(np.unique(exp_ds.time.values))
        else:
            if not all(t in exp_ds.time.values for t in self.sel_time):
                raise ValueError(
                    f"""
                    Selected time steps {self.sel_time} are not present in the dataset.
                    Available time steps: {np.unique(exp_ds.time.values)}
                    """
                )
        self.sel_idxs = (
            exp_ds.band.isin(self.sel_band).values
            & exp_ds.time.isin(self.sel_time).values
        )

        # sanity checks
        if self.check_congruence:

            # 1) check number of files indicated in meta file vs. data directory
            label_files = [
                os.path.join(self.label_dir, f)
                for f in os.listdir(self.label_dir)
                if f.endswith(".tif") or f.endswith(".vrt")
            ]
            data_files = [
                os.path.join(self.data_dir, f)
                for f in os.listdir(self.data_dir)
                if f.endswith(".tif") or f.endswith(".vrt")
            ]
            if (
                not len(
                    np.unique(
                        np.array(
                            [
                                len(self.meta_file),
                                len(data_files),
                                len(label_files),
                            ]
                        )
                    )
                )
                == 1
            ):
                raise ValueError(
                    f"""
                        Number of entries in metadata (n={len(self.meta_file)})
                        does not match number of files in data directory '{self.data_dir}' (n={len(data_files)})
                        or does not match number of files in label directory '{self.label_dir}' (n={len(label_files)})
                    """
                )

            # 2) check if labels are as expected
            for _, row in tqdm(self.meta_file.iterrows()):
                arr_path = row["label_path"]
                arr_vals = np.unique(rxr.open_rasterio(arr_path).values)
                if not pd.Series(arr_vals).isin(self.label_map_df["int_given"]).all():
                    raise ValueError(
                        "Labels defined in mapping and arrays do not match."
                        f"\nArray at {arr_path} contains values {arr_vals}."
                        f"\nExpected values: {self.label_map_df['int_given'].values}.\n"
                    )

    def __len__(self):
        return len(self.meta_file)

    @abstractmethod
    def __getitem__(self, idx):
        """
        Must be implemented by subclass.
        Should return a tuple of (input, label) for the given index.
        """
        pass

    def plot(self, idx=None, seed=42):
        """
        Plot samples from the dataset.

        Args:
            idx (int, optional): Index of the sample to plot. If None, 5 random samples are selected.
            seed (int, optional): Random seed for reproducibility. Defaults to 42.
        """
        # get rgb version of dataset
        rgb_instance = self.__class__(
            meta_file=self.meta_file,
            input_data_dir=self.data_dir,
            label_data_dir=self.label_dir,
            sel_time=[self.sel_time[0]],
            sel_band=self.RGB_BANDS,
            data_transform=self.data_transform,
            data_usage=self.data_usage,
            check_congruence=self.check_congruence,
        )

        # define sample idxs
        if idx is not None:
            sample_idxs = [idx]
        else:
            np.random.seed(seed)
            sample_idxs = np.random.choice(np.arange(len(self)), 5, replace=False)

        # fetch data and labels
        data_arr = []
        label_arr = []
        for idx in sample_idxs:
            data, label = rgb_instance[idx]
            data_arr.append(data)
            label_arr.append(label)

        # wrap as xarray for convenient plotting
        data_arr = np.stack(data_arr, axis=0)
        data_arr = xr.DataArray(data_arr, dims=["sample", "band", "y", "x"])
        label_arr = np.stack(label_arr, axis=0)
        label_arr = xr.DataArray(label_arr, dims=["sample", "y", "x"])

        # compute robust normalization globally
        vmin, vmax = np.percentile(
            data_arr.transpose("sample", "y", "x", "band").values, [2, 98]
        )

        # setup figure
        n = len(sample_idxs)
        fig, axs = plt.subplots(2, n, figsize=(3 * n, 6), constrained_layout=True)

        # ensure axs is always 2D (2 x n)
        if n == 1:
            axs = np.expand_dims(axs, axis=1)

        # plot all samples
        for i in range(n):
            img = data_arr.isel(sample=i).transpose("y", "x", "band").values
            img = np.clip((img - vmin) / (vmax - vmin + 1e-6), 0, 1)
            axs[0, i].imshow(img, cmap="Greys" if img.shape[-1] == 1 else None)
            axs[0, i].set_title(f"Image #{sample_idxs[i]}")
            axs[0, i].axis("off")

            axs[1, i].imshow(
                label_arr.isel(sample=i).values,
                interpolation="nearest",
                cmap=self.label_cmap,
                vmin=0,
                vmax=self.label_map_df["int_target"].max(),
            )
            axs[1, i].set_title(f"Label #{sample_idxs[i]}")
            axs[1, i].axis("off")

        # build legend
        handles = [
            Patch(color=row["color"], label=row["str_short"])
            for _, row in self.label_map_df.drop_duplicates("int_target")
            .sort_values("int_target")
            .iterrows()
        ]

        fig.legend(
            handles,
            [h.get_label() for h in handles],
            loc="lower center",
            ncol=len(handles),
            frameon=False,
            fontsize="medium",
            bbox_to_anchor=(0.5, -0.05),
        )
        plt.show()

    def _get_label_map(self, binary=False):
        """
        Defines a mapping of label indices to their corresponding information.

        Args:
            binary (bool): If True, returns a binary label mapping.
                If False, returns the full label mapping.
        """
        # define label mapping
        # index: (int_given, int_target, str_short, str_long, color)
        label_map_full = {
            0: (0, 0, "NA", "no LRT", "#7d7d7d"),
            1: (2, 1, "6210", "Naturnahe Kalk-Trockenrasen", "#f29b52"),
            2: (1, 2, "6510", "Magere Flachland-Mähwiesen", "#61ab76"),
            3: (3, 3, "6520", "Berg-Mähwiesen", "#0e8a48"),
            4: (4, 4, "9110", "Hainsimsen-Buchenwald", "#4a1244"),
            5: (5, 5, "9180", "Schlucht- und Hangmischwälder", "#541005"),
        }
        label_map_binary = {
            0: (0, 0, "NA", "no LRT", "#7d7d7d"),
            1: (1, 1, "habitat", "habitat", "#61ab76"),
            2: (2, 1, "habitat", "habitat", "#61ab76"),
            3: (3, 1, "habitat", "habitat", "#61ab76"),
            4: (4, 1, "habitat", "habitat", "#61ab76"),
            5: (5, 1, "habitat", "habitat", "#61ab76"),
        }

        if binary:
            self.label_map = label_map_binary
        else:
            self.label_map = label_map_full

        # label mapping as DataFrame
        self.label_map_df = pd.DataFrame.from_dict(
            self.label_map,
            orient="index",
            columns=["int_given", "int_target", "str_short", "str_long", "color"],
        )
        self.labels_unique = self.label_map_df["int_target"].unique()

        # label mapping as look-up-table for on-the-fly conversion
        orig = self.label_map_df["int_given"].values
        target = self.label_map_df["int_target"].values
        max_val = self.label_map_df["int_given"].max()
        self.label_map_lut = np.zeros(max_val + 1, dtype=int)
        self.label_map_lut[orig] = target

        # colormap for plotting
        target_colors_df = (
            self.label_map_df.drop_duplicates("int_target")
            .sort_values("int_target")
            .reset_index(drop=True)
        )
        hex_colors = target_colors_df["color"].tolist()
        self.label_cmap = ListedColormap(hex_colors)

    @staticmethod
    def _get_source_filenames_from_vrt(vrt_path):
        """Extract source filenames from a VRT file."""
        tree = ET.parse(vrt_path)
        root = tree.getroot()
        filenames = []
        for band in root.findall("VRTRasterBand"):
            source = band.find("ComplexSource")
            filename = source.find("SourceFilename").text
            filenames.append(filename)
        return filenames

    @staticmethod
    @abstractmethod
    def _parse_filenames(filenames):
        """
        Must be implemented by subclass.
        Should return a list of tuples (time,band) extracting the time and band
        information from the filepath of a given patch.
        """
        pass


class S2_Dataset(BaseDataset):
    RGB_BANDS = ["B4", "B3", "B2"]

    def __init__(
        self,
        meta_file,
        phase="train",
        fold=0,
        input_data_dir=None,
        label_data_dir=None,
        sel_time=None,
        sel_band=None,
        transform=None,
        data_transform=None,
        data_usage=0,
        check_congruence=False,
    ):
        super().__init__(
            meta_file=meta_file,
            input_data_dir=input_data_dir,
            label_data_dir=label_data_dir,
            sel_time=sel_time,
            sel_band=sel_band,
            data_transform=data_transform,
            data_usage=data_usage,
            check_congruence=check_congruence,
        )

        self.img_path = []
        self.label_path = []
        self.labels = []
        self.transform = transform

        # compute labels
        for idx in range(len(self.meta_file)):
            row = self.meta_file.iloc[idx]
            if row[f"fold_{fold}"] == phase:
                label_ds = rxr.open_rasterio(row["label_path"])
                label_arr = self.label_map_lut[label_ds.values.astype(int)]
                label_arr = torch.from_numpy(label_arr[0]).to(torch.float32)
                label_int = 1 if torch.mean(label_arr) > 0.2 else 0
                self.img_path.append(row["input_path"])
                self.label_path.append(row["label_path"])
                self.labels.append(label_int)

        # get image number list
        occur_dict = dict(Counter(self.labels))
        self.cls_num_list = [occur_dict[i] for i in sorted(occur_dict.keys())]

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        in_ds = rxr.open_rasterio(self.img_path[idx])
        in_arr = in_ds[self.sel_idxs].values.astype(float)
        in_arr /= 10000
        label_ds = rxr.open_rasterio(self.label_path[idx])
        label_arr = self.label_map_lut[label_ds.values.astype(int)]
        label_arr = label_arr[0]
        in_arr = torch.from_numpy(in_arr).to(torch.float32)
        label = self.labels[idx]
        if self.transform is not None:
            sample = self.transform(in_arr)
        return sample, label  # , index

    @staticmethod
    def _parse_filenames(filenames):
        """Parse Sentinel-2 filenames to extract date & band information."""
        parsed_filenames = []
        for filename in filenames:
            file_parts = os.path.split(filename)[-1].split("_")
            time = file_parts[1].split("-")[0]
            band = file_parts[7]
            parsed_filenames.append((time, band))
        return parsed_filenames


